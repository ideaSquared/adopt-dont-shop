import type { Page } from '@playwright/test';

import { test, expect } from '../../fixtures';
import { dismissCookieBannerPatiently } from '../../helpers/cookie-banner-patient';
import { uniqueText } from '../../helpers/factories';
import { skipSwipeIntro } from '../../helpers/swipe-intro';
import { URLS } from '../../playwright.config';

/**
 * Content management: an admin creates a blog post (a draft), publishes it so
 * visitors can read it on the client blog, then unpublishes it and it goes
 * away again (ADM-120).
 */

const createBlogDraft = async (page: Page, title: string, body: string): Promise<void> => {
  await page.goto('/content-management');
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible({ timeout: 30_000 });
  await page.getByRole('button', { name: 'New Content' }).click();
  await page.getByRole('textbox', { name: 'Title *' }).fill(title);
  // The slug is generated by the server when the title loses focus.
  await page.getByRole('textbox', { name: 'Content (HTML) *' }).focus();
  await expect(page.getByLabel(/^Slug/)).not.toHaveValue('');
  await page.getByRole('combobox', { name: 'Content Type' }).selectOption({ label: 'Blog Post' });
  await page.getByRole('textbox', { name: 'Content (HTML) *' }).fill(`<p>${body}</p>`);
  await page.getByRole('textbox', { name: 'Excerpt' }).fill('A short read for the E2E suite');
  await page.getByRole('button', { name: 'Create Content' }).click();
};

test.describe('blog post lifecycle in content management', () => {
  test('a new post is a draft that visitors cannot see; publishing shows it, unpublishing hides it', async ({
    page,
    browser,
  }) => {
    const title = uniqueText('Seasonal adoption tips');
    const body = 'Autumn is a lovely time to bring a new pet home.';
    await dismissCookieBannerPatiently(page);
    await createBlogDraft(page, title, body);

    const row = page.getByRole('row').filter({ hasText: title });
    await expect(row.getByRole('cell', { name: 'draft' })).toBeVisible({ timeout: 15_000 });
    await expect(row.getByRole('cell', { name: 'Blog Post' })).toBeVisible();
    const slug = ((await row.getByRole('cell').nth(1).textContent()) ?? '').replace(/^\//, '');
    expect(slug).not.toBe('');

    const visitorContext = await browser.newContext({
      baseURL: URLS.client,
      storageState: { cookies: [], origins: [] },
    });
    try {
      const visitor = await visitorContext.newPage();
      await skipSwipeIntro(visitor);
      await dismissCookieBannerPatiently(visitor);
      const postLink = visitor.getByRole('link', { name: new RegExp(title) });

      await visitor.goto('/blog');
      await expect(visitor.getByRole('heading', { level: 1, name: 'Blog' })).toBeVisible({
        timeout: 30_000,
      });
      // The heading renders while posts are still loading; only a loaded list can prove absence.
      await expect(visitor.getByRole('status', { name: 'Loading posts' })).toHaveCount(0, {
        timeout: 30_000,
      });
      await expect(postLink).toHaveCount(0);

      await row.getByRole('button', { name: 'Publish' }).click();
      await expect(row.getByRole('cell', { name: 'published' })).toBeVisible({ timeout: 15_000 });

      await visitor.goto('/blog');
      await expect(postLink.first()).toBeVisible({ timeout: 30_000 });
      await visitor.goto(`/blog/${slug}`);
      await expect(visitor.getByRole('heading', { name: title })).toBeVisible({ timeout: 15_000 });
      await expect(visitor.getByText(body)).toBeVisible();

      await row.getByRole('button', { name: 'Unpublish' }).click();
      await expect(row.getByRole('cell', { name: 'draft' })).toBeVisible({ timeout: 15_000 });
      await expect(row.getByRole('button', { name: 'Publish' })).toBeVisible();

      await visitor.goto('/blog');
      await expect(visitor.getByRole('heading', { level: 1, name: 'Blog' })).toBeVisible({
        timeout: 30_000,
      });
      // The heading renders while posts are still loading; only a loaded list can prove absence.
      await expect(visitor.getByRole('status', { name: 'Loading posts' })).toHaveCount(0, {
        timeout: 30_000,
      });
      await expect(postLink).toHaveCount(0);
      await visitor.goto(`/blog/${slug}`);
      // The client sends a deep link to an unpublished post back to the blog index.
      await expect(visitor).toHaveURL(/\/blog$/, { timeout: 15_000 });
      await expect(visitor.getByText(body)).toHaveCount(0);
    } finally {
      await visitorContext.close();
    }

    // Clean up: remove the throwaway post.
    await row.getByRole('button', { name: 'Delete' }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Delete', exact: true }).click();
    await expect(row).toHaveCount(0, { timeout: 15_000 });
  });
});
